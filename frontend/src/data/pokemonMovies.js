export const getMovieById = (idOrSlug) => {
  if (!idOrSlug) return null;
  const str = String(idOrSlug).toLowerCase().trim();
  return POKEMON_MOVIES.find(
    (m) =>
      String(m.id) === str ||
      m.slug === str ||
      String(m.movieNumber) === str ||
      m.title.toLowerCase().includes(str)
  );
};
